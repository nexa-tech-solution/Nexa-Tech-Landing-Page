// Checks each mobile app's `marketing.aso` block in data.ts against store limits
// and writes docs/aso-report.md. Run: npm run aso:check
import fs from "node:fs";
import path from "node:path";
import { projects, getProjectSlug } from "../client/src/components/nexa/data";

const LIMITS = { title: 30, subtitle: 30, iosKeywords: 100, playShort: 80 };

const words = (text: string) =>
  text
    .toLowerCase()
    .split(/[^a-z0-9à-ỹ]+/i)
    .filter((w) => w.length > 1);

// iOS indexes title + subtitle + keyword field together, so any word already in
// title/subtitle is wasted in the keyword field. Plurals/duplicates are wasted too.
function iosKeywordField(title: string, subtitle: string, keywords: string[]) {
  const used = new Set([...words(title), ...words(subtitle)]);
  const out: string[] = [];
  const wasted: string[] = [];
  for (const word of keywords.flatMap(words)) {
    if (used.has(word)) {
      if (!out.includes(word)) wasted.push(word);
      continue;
    }
    used.add(word);
    out.push(word);
  }
  return { field: out.join(","), wasted: [...new Set(wasted)] };
}

const rows: string[] = [];
const details: string[] = [];
let issues = 0;

for (const project of projects.filter((p) => p.category === "Mobile")) {
  const aso = project.marketing?.aso;
  const slug = getProjectSlug(project);
  if (!aso) {
    rows.push(`| ${project.title} | – | – | – | – | no aso block |`);
    issues++;
    continue;
  }
  const { field, wasted } = iosKeywordField(aso.title, aso.subtitle, aso.keywords);
  const main = aso.keywords[0] ?? "";
  const titleHasKeyword = words(main).some((w) => words(aso.title).includes(w));
  const problems = [
    aso.title.length > LIMITS.title && `title ${aso.title.length}>${LIMITS.title}`,
    aso.subtitle.length > LIMITS.subtitle && `subtitle ${aso.subtitle.length}>${LIMITS.subtitle}`,
    field.length > LIMITS.iosKeywords && `keywords ${field.length}>${LIMITS.iosKeywords}`,
    aso.description.length > LIMITS.playShort && `short desc ${aso.description.length}>${LIMITS.playShort}`,
    !titleHasKeyword && `title missing main keyword "${main}"`,
    aso.title.length < 20 && `title uses ${aso.title.length}/30 chars`,
    field.length < 70 && `keyword field uses ${field.length}/100 chars`,
  ].filter(Boolean) as string[];
  issues += problems.length;

  rows.push(
    `| [${project.title}](../client/public) | ${aso.title.length}/30 | ${aso.subtitle.length}/30 | ${field.length}/100 | ${aso.description.length}/80 | ${problems.join("; ") || "✓"} |`.replace(
      "](../client/public)",
      `](/work/${slug})`,
    ),
  );
  details.push(
    [
      `### ${project.title}`,
      `- Title: \`${aso.title}\``,
      `- Subtitle: \`${aso.subtitle}\``,
      `- iOS keyword field (deduped, no spaces): \`${field}\``,
      wasted.length ? `- Already in title/subtitle (removed): ${wasted.join(", ")}` : "",
      `- Play short description: \`${aso.description}\``,
    ]
      .filter(Boolean)
      .join("\n"),
  );
}

const report = `# ASO report

Generated by \`npm run aso:check\` from \`marketing.aso\` in \`client/src/components/nexa/data.ts\`.
Limits: title ${LIMITS.title}, subtitle ${LIMITS.subtitle}, iOS keyword field ${LIMITS.iosKeywords}, Play short description ${LIMITS.playShort}.
Keep this data in sync with what is live in App Store Connect / Play Console.

| App | Title | Subtitle | iOS keywords | Play short | Issues |
|-----|-------|----------|--------------|------------|--------|
${rows.join("\n")}

${details.join("\n\n")}
`;

const out = path.resolve(import.meta.dirname, "..", "docs", "aso-report.md");
fs.writeFileSync(out, report);
console.log(`[aso] ${rows.length} apps, ${issues} issues → docs/aso-report.md`);
